defmodule ExTLA.Surface do
  @moduledoc """
  The one drift check every surface golden shares (#270).

  `mix tla.coverage --check` had this as a private function until `API_SURFACE.md` needed the
  same three outcomes — current, drifted, missing — and the alternative was a second copy of a
  gate, which is how two gates come to disagree about what "drifted" means. The message carries
  the remedy: a gate that fails without saying what to run is one somebody works around.
  """

  @doc """
  Compare the golden at `path` with `rendered`, for the golden `name` regenerated by `task`.
  Raises `Mix.Error` on drift or absence; says so on the shell when current.
  """
  def check!(name, task, path, rendered) do
    case File.read(path) do
      {:ok, ^rendered} ->
        Mix.shell().info("#{name} is current")

      {:ok, _stale} ->
        Mix.raise("#{name} has drifted from the source. Regenerate: mix #{task} --write")

      {:error, :enoent} ->
        Mix.raise("#{name} is missing. Generate it: mix #{task} --write")
    end
  end
end
