defmodule TLA.StateGraph do
  @moduledoc """
  The state graph built during model checking. Nodes are states, edges are
  labeled transitions.

  ## Memory model: fingerprints and parent pointers, not states

  The graph does NOT retain the states it has explored. Each visited state
  contributes one fixed-size record:

      fingerprint => {state_id, parent_id, action_name, params}

  A state is materialized only while its successors are being computed, and then
  discarded. When a trace is needed — once, on violation — the path is walked
  back to an initial state through the parent pointers and the states are
  regenerated by replaying the recorded actions forward from `init`.

  An earlier draft stored every state for the whole run. At the 10M-state target
  and roughly 1KB per state that is about 10GB of RAM, which puts the checker out
  of reach of the machines people actually have. The record above is on the order
  of 64 bytes regardless of how large a state is, so memory becomes a function of
  the state *count* rather than of state *size* — and trace generation, which
  happens at most once per run, pays the replay cost instead. This is the same
  trade TLC makes (D-5).

  The consequence to be aware of: a spec whose actions are expensive to apply
  pays that cost twice on the failing path. That is the right place for it to
  fall.

  ## Why the graph carries the spec and the constants

  Replay needs them. `path_to/2` recovers a list of `{action, params}`, and
  turning that back into states means running `init` and then each action —
  which cannot be done from the identifiers alone. `04-layer2-model-checker.md`
  typed `TLA.Trace.generate/2` as taking only the graph and a state id, so the
  graph is where they have to live.

  ## Why an initial state records which `init` produced it

  Several `init` blocks are disjuncted (`02-dsl-semantics.md`), so replay has to
  know which one to run for the root of the path. `node_record.init_index`
  carries it; it is `nil` for every non-initial state, where `action` and
  `params` say what happened instead.

  ## The liveness graph is a separate, opt-in structure

  Parent pointers are a spanning *tree*: every node has one in-edge, the tree is
  acyclic by construction, and no cycle of the real graph is visible in it.
  Liveness checking is cycle detection, so this record cannot support it — which
  is why `successors/2` reads an edge table and raises when there is none, rather
  than deriving something wrong from parent pointers.

  So a run that asks for it records, additionally, per expanded state:

      state_id => [{action, params, successor_id}]   # every out-edge
      state_id => enabled_bits                       # one bit per fairness constraint

  The edge table is what an SCC search runs over. The bits are what fairness needs: WF
  and SF are conditions on `ENABLED A` at each state of a cycle, which is a function of
  the state — and the state is discarded as soon as it has been expanded, so the bit has
  to be taken while it is still in hand. They are indexed by `fairness_index`, the §5.2
  expansion of the spec's `fairness` declarations (`TLA.Temporal.Fairness`).

  Cost is a function of the branching factor and of how large a binding is — an action
  whose param is a message record carries that record in every edge — but not of how
  large a *state* is, which is the property D-5 exists to keep. It is opt-in for that
  reason and paid for only when asked for, which is TLC's split too.

  Only an **expanded** state has edges. A run that stopped early — `max_states`, a state
  constraint holding states back, a safety violation halting the search — leaves a
  partial edge table, and a liveness verdict read off a partial graph would be a claim
  about behaviours that were never explored. Checking one is a completed run's privilege.

  ## ETS

  `nodes` and `fingerprints` are ETS tables, owned by the process that called
  `new/3` and deleted when it exits. The struct itself carries only the table
  identifiers and the counters, so `add_state/5` returning an updated struct is
  about the counters; the tables are mutated in place. That is the shape the
  parallel checker of Phase 4 needs, and it costs nothing here.
  """

  alias TLA.{Fingerprint, State, Symmetry}

  @type state_id :: non_neg_integer()

  @type node_record :: %{
          parent: state_id() | nil,
          action: atom() | nil,
          params: map() | nil,
          init_index: non_neg_integer() | nil,
          depth: pos_integer()
        }

  @type edge :: {action :: atom(), params :: map(), successor :: state_id()}

  @type t :: %__MODULE__{
          spec: TLA.Spec.Compiled.t(),
          constants: map(),
          fingerprint_bits: 64 | 128,

          # The permutations of `04-layer2-model-checker.md` §Symmetry, or nil. Present,
          # they are what a state is canonicalized under before it is fingerprinted, so
          # two symmetric states are one state.
          symmetry: [Symmetry.mapping()] | nil,
          nodes: :ets.table(),
          fingerprints: :ets.table(),

          # The id allocator, as an atomic rather than a counter in this struct: a second
          # process cannot allocate from a field of an immutable term. `:atomics` is the
          # smallest thing that is shared and race-free.
          ids: :atomics.atomics_ref(),
          initial_states: MapSet.t(state_id()),
          deadlocked: MapSet.t(state_id()),
          terminal: MapSet.t(state_id()),
          # These six are still per-struct, and deliberately (#31). Each worker would
          # accumulate its own and they would have to be merged, which is a decision the
          # COORDINATOR makes — and there is no coordinator yet to constrain the answer.
          # Phase 4 moves them, or decides not to.
          state_count: non_neg_integer(),
          transition_count: non_neg_integer(),
          diameter: non_neg_integer(),

          # Present only when built with check_liveness: true; nil otherwise.
          edges: %{state_id() => [edge()]} | nil,
          enabled: %{state_id() => bitstring()} | nil,
          fairness_index: [{TLA.Spec.Compiled.fairness_def(), map()}] | nil
        }

  @enforce_keys [:spec, :constants, :nodes, :fingerprints, :ids]
  defstruct [
    :spec,
    :constants,
    :nodes,
    :fingerprints,
    :ids,
    fingerprint_bits: 64,
    symmetry: nil,
    initial_states: MapSet.new(),
    deadlocked: MapSet.new(),
    terminal: MapSet.new(),
    state_count: 0,
    transition_count: 0,
    diameter: 0,
    edges: nil,
    enabled: nil,
    fairness_index: nil
  ]

  @doc """
  Turn on the liveness graph, with the fairness constraints its enabled bits are indexed
  by — `TLA.Temporal.Fairness.expand/3`, which needs the constants and so cannot run
  until a state exists.

  A spec with no `fairness` declarations still gets a liveness graph, with zero-width
  bits: the edge table alone answers `always`, `eventually` and `~>`; fairness is what
  the bits are for.
  """
  @spec with_liveness(t(), [TLA.Temporal.Fairness.constraint()]) :: t()
  def with_liveness(graph, fairness_index) do
    %{graph | edges: %{}, enabled: %{}, fairness_index: fairness_index}
  end

  @doc """
  Whether this graph carries the liveness structure.
  """
  @spec liveness?(t()) :: boolean()
  def liveness?(%__MODULE__{edges: edges}), do: edges != nil

  @doc """
  Record a state's out-edges and its enabled bits. Called once per expanded state; a
  no-op on a safety-only graph, so the caller does not branch.

  Every out-edge, including the ones that led to a state already seen — those are exactly
  the edges that close a cycle, and a cycle is what liveness checking is looking for.
  """
  @spec add_edges(t(), state_id(), [edge()], bitstring()) :: t()
  def add_edges(graph, id, edges, enabled)

  def add_edges(%__MODULE__{edges: nil} = graph, _id, _edges, _enabled), do: graph

  def add_edges(graph, id, edges, enabled) do
    %{
      graph
      | edges: Map.put(graph.edges, id, edges),
        enabled: Map.put(graph.enabled, id, enabled)
    }
  end

  @doc """
  The ENABLED bits of a state, in `fairness_index` order.
  """
  @spec enabled_bits(t(), state_id()) :: bitstring()
  def enabled_bits(%__MODULE__{enabled: nil}, _id), do: raise(no_liveness_graph())

  def enabled_bits(%__MODULE__{enabled: enabled}, id), do: Map.get(enabled, id, <<>>)

  @doc """
  Whether the `index`th fairness constraint was enabled in a state.
  """
  @spec enabled?(t(), state_id(), non_neg_integer()) :: boolean()
  def enabled?(graph, id, index) do
    case enabled_bits(graph, id) do
      <<_::size(^index), bit::1, _::bitstring>> -> bit == 1
      _ -> false
    end
  end

  @doc """
  A new, empty graph for `spec` under `constants`.
  """
  @spec new(TLA.Spec.Compiled.t(), map(), keyword()) :: t()
  def new(spec, constants, opts \\ []) do
    %__MODULE__{
      spec: spec,
      constants: constants,
      fingerprint_bits: Keyword.get(opts, :fingerprint_bits, 64),
      symmetry: Keyword.get(opts, :symmetry),
      # `:public`, not `:protected`: a process that is not the owner cannot write to a
      # protected table AT ALL, so parallel exploration is impossible before this line
      # changes. It is also free — measured at 0.97x of protected on a single-writer
      # insert-and-lookup loop, which is noise.
      #
      # `write_concurrency` is NOT set, and that is a measurement rather than an oversight.
      # It costs 1.39x on that same loop (`:auto` costs 1.68x), and buys nothing until
      # there are concurrent writers — while `bench/search_profile.baseline.md` puts the
      # ETS lookup and insert at 0.2% of the raft search. What lock granularity a
      # coordinator wants depends on how it batches and shards its writes, which is a
      # Phase 4 decision with no consumer here to constrain it. Setting it now would be
      # paying 39% on the one structure the profile says is already free.
      nodes: :ets.new(:tla_nodes, [:set, :public, read_concurrency: true]),
      fingerprints: :ets.new(:tla_fingerprints, [:set, :public, read_concurrency: true]),
      ids: :atomics.new(1, signed: false)
    }
  end

  @doc """
  Register a state by fingerprint, returning its id and whether it is new. The
  state itself is not retained.

  `parent` is `nil` for an initial state, in which case `action` is the index of
  the `init` block that produced it.
  """
  @spec add_state(t(), State.t(), state_id() | nil, atom() | non_neg_integer(), map() | nil) ::
          {t(), state_id(), :new | :existing}
  def add_state(graph, state, parent, action, params)

  def add_state(graph, state, nil, init_index, _params) when is_integer(init_index) do
    insert(graph, state, %{
      parent: nil,
      action: nil,
      params: nil,
      init_index: init_index,
      depth: 1
    })
  end

  def add_state(graph, state, parent, action, params) when is_integer(parent) do
    insert(graph, state, %{
      parent: parent,
      action: action,
      params: params,
      init_index: nil,
      depth: depth(graph, parent) + 1
    })
  end

  # Race-free by construction rather than by being single-threaded. The lookup is still
  # first because it is the common case and it is cheap; what makes the insertion safe is
  # `insert_new/2`, which is atomic: two processes that both miss the lookup do not both
  # get to claim the fingerprint. The loser reads the winner's id and reports `:existing`,
  # which is exactly what it would have reported had the lookup found it.
  #
  # The id it allocated is then unused, so ids have gaps under contention. Nothing reads
  # them as a range — they are keys — and an id is never reused, which is the property
  # that matters: a trace names states by id.
  defp insert(graph, state, record) do
    fingerprint = fingerprint(graph, state)

    case :ets.lookup(graph.fingerprints, fingerprint) do
      [{^fingerprint, id}] ->
        {graph, id, :existing}

      [] ->
        claim(graph, fingerprint, record)
    end
  end

  defp claim(graph, fingerprint, record) do
    id = :atomics.add_get(graph.ids, 1, 1) - 1

    if :ets.insert_new(graph.fingerprints, {fingerprint, id}) do
      :ets.insert(graph.nodes, {id, record})

      graph = %{
        graph
        | state_count: graph.state_count + 1,
          diameter: max(graph.diameter, record.depth),
          initial_states:
            if(record.parent == nil,
              do: MapSet.put(graph.initial_states, id),
              else: graph.initial_states
            )
      }

      {graph, id, :new}
    else
      [{^fingerprint, winner}] = :ets.lookup(graph.fingerprints, fingerprint)
      {graph, winner, :existing}
    end
  end

  # Under symmetry a state is identified by the smallest encoding of any permutation of
  # it, so the FIRST of an orbit to be discovered is the one the graph keeps — parent
  # pointers, edges and traces are all about that representative, and replay produces a
  # genuine behaviour of the spec rather than a canonicalized stand-in.
  defp fingerprint(%__MODULE__{symmetry: nil} = graph, state),
    do: Fingerprint.compute(state, bits: graph.fingerprint_bits)

  defp fingerprint(graph, state) do
    state
    |> Symmetry.canonical(graph.symmetry)
    |> Fingerprint.of_encoding(bits: graph.fingerprint_bits)
  end

  @doc """
  The node record for a state id.
  """
  @spec node_record(t(), state_id()) :: node_record()
  def node_record(graph, id) do
    case :ets.lookup(graph.nodes, id) do
      [{^id, record}] -> record
      [] -> raise ArgumentError, "no such state id: #{inspect(id)}"
    end
  end

  @doc """
  The BFS level of a state: 1 for an initial state, one more than its parent
  otherwise. Equal to the number of states on the shortest path to it, which is
  the number TLC reports as a counterexample's length.
  """
  @spec depth(t(), state_id()) :: pos_integer()
  def depth(graph, id), do: node_record(graph, id).depth

  @doc """
  Count one transition, whether or not it discovered a new state.
  """
  @spec count_transition(t()) :: t()
  def count_transition(graph), do: %{graph | transition_count: graph.transition_count + 1}

  @doc """
  Mark an expanded state that has no successors.
  """
  @spec mark_terminal(t(), state_id()) :: t()
  def mark_terminal(graph, id), do: %{graph | terminal: MapSet.put(graph.terminal, id)}

  @doc """
  Mark an expanded state that has no successors and that no `terminal` predicate
  admits.
  """
  @spec mark_deadlocked(t(), state_id()) :: t()
  def mark_deadlocked(graph, id), do: %{graph | deadlocked: MapSet.put(graph.deadlocked, id)}

  @doc """
  The action path from an initial state to the target, walked through parent
  pointers. `TLA.Trace` replays this to regenerate the states themselves.

  The first element is the `init` block that produced the root.
  """
  @spec path_to(t(), state_id()) :: {init_index :: non_neg_integer(), [{atom(), map()}]}
  def path_to(graph, target), do: walk_back(graph, target, [])

  defp walk_back(graph, id, steps) do
    case node_record(graph, id) do
      %{parent: nil, init_index: index} ->
        {index, steps}

      %{parent: parent, action: action, params: params} ->
        walk_back(graph, parent, [{action, params} | steps])
    end
  end

  @doc """
  Successors of a state, from the edge table.

  Raises when the graph was built without `check_liveness: true`: there is no
  cheaper source, and guessing from parent pointers would be wrong — they form a
  spanning tree, which has no cycles at all.
  """
  @spec successors(t(), state_id()) :: [edge()]
  def successors(%__MODULE__{edges: nil}, _id), do: raise(no_liveness_graph())

  def successors(%__MODULE__{edges: edges}, id), do: Map.get(edges, id, [])

  @doc """
  Every strongly connected component of the edge table, as sets of state ids.

  Tarjan's algorithm, in ids order so a run's components — and therefore any
  counterexample read off them — are the same every time.

  A component is *maximal*: it is every state mutually reachable from every other. That
  says nothing on its own about whether a behaviour can cycle in it, which is a question
  about the spec's fairness and belongs to `TLA.ModelChecker.Liveness`. A state with no
  out-edges comes back as a component of one, and whether stuttering there forever counts
  as a cycle is the same kind of question (`02-dsl-semantics.md` §5.3).
  """
  @spec sccs(t()) :: [MapSet.t(state_id())]
  def sccs(%__MODULE__{} = graph), do: sccs(graph, MapSet.new(0..(graph.state_count - 1)//1))

  @doc """
  The same, over a subset of the states — the edges to anything outside it are ignored.

  Liveness checking asks this of the subgraph where a property is false, and again of
  smaller subgraphs as strong fairness rules components out
  (`04-layer2-model-checker.md` §`TLA.ModelChecker.Liveness`).
  """
  @spec sccs(t(), MapSet.t(state_id())) :: [MapSet.t(state_id())]
  def sccs(%__MODULE__{edges: nil}, _region), do: raise(no_liveness_graph())

  def sccs(graph, region) do
    region
    |> Enum.sort()
    |> Enum.reduce(
      %{index: 0, indices: %{}, low: %{}, stack: [], on: MapSet.new(), out: []},
      fn id, acc ->
        if Map.has_key?(acc.indices, id), do: acc, else: connect(graph, region, id, acc)
      end
    )
    |> Map.fetch!(:out)
    |> Enum.reverse()
  end

  defp connect(graph, region, v, acc) do
    acc = %{
      acc
      | indices: Map.put(acc.indices, v, acc.index),
        low: Map.put(acc.low, v, acc.index),
        index: acc.index + 1,
        stack: [v | acc.stack],
        on: MapSet.put(acc.on, v)
    }

    acc =
      graph
      |> successors(v)
      |> Enum.reduce(acc, fn {_action, _params, w}, acc ->
        cond do
          not MapSet.member?(region, w) ->
            acc

          not Map.has_key?(acc.indices, w) ->
            acc = connect(graph, region, w, acc)
            %{acc | low: Map.put(acc.low, v, min(acc.low[v], acc.low[w]))}

          MapSet.member?(acc.on, w) ->
            %{acc | low: Map.put(acc.low, v, min(acc.low[v], acc.indices[w]))}

          true ->
            acc
        end
      end)

    if acc.low[v] == acc.indices[v], do: pop_component(acc, v), else: acc
  end

  defp pop_component(acc, v) do
    {above, [^v | rest]} = Enum.split_while(acc.stack, &(&1 != v))
    component = MapSet.new([v | above])

    %{acc | stack: rest, on: MapSet.difference(acc.on, component), out: [component | acc.out]}
  end

  defp no_liveness_graph do
    %ArgumentError{
      message:
        "no liveness graph: this graph was built without it, so it has no edge table and " <>
          "no enabled bits. Parent pointers are a spanning tree and cannot answer this. " <>
          "Explore with `liveness_graph: true`."
    }
  end
end
