defmodule Mix.Tasks.Extla.Visualize do
  @shortdoc "Render a spec's state graph as DOT"

  @moduledoc """
  Render a `ExTLA.Spec` module's state graph as DOT, for Graphviz.

  ## Usage

      mix extla.visualize Specs.TransferProtocol
      mix extla.visualize Specs.TransferProtocol --output graph.dot
      mix extla.visualize Specs.TransferProtocol --max-states 2000

      mix extla.visualize Specs.X --output g.dot && dot -Tsvg g.dot -o g.svg

  Constants come from the same two places `mix extla.check` takes them from, in the
  same order of precedence, and a constant with neither is the same error.

  ## What it draws

  Every reachable state as a node labelled with its variables, and every transition as an
  edge labelled with its action and that action's parameter binding. Initial states carry a
  double border, declared `terminal` states a doubled octagon, and deadlocked states a
  fill.

  **A spec whose invariant is refuted is drawn with its counterexample emphasised**, and
  the run says so. That graph is *partial* — the search stopped at the violation — which is
  the honest picture of what was explored rather than of the whole state space.

  ## Options

      --output       Write here instead of to stdout.
      --max-states   How many states to explore, and therefore at most how many
                     to draw (default #{ExTLA.StateGraph.Export.default_max_states()}).
      --format       dot, and only dot. See below.

  ## Why DOT only

  DOT is enough: Graphviz renders it to SVG, PNG or PDF, and a bespoke viewer would be one
  more thing to maintain. A `--format html` or `--format mermaid` is refused with a message
  saying so rather than silently ignored.

  ## Why it refuses a large graph, and why the search stops there too

  Node labels are regenerated by replay, because the state graph keeps fingerprints rather
  than states, and a layout engine given tens of thousands of nodes returns a hairball
  rather than a picture.
  Past `--max-states` the task refuses: rendering the first 500 of 58,359 would hand back
  something that looks complete.

  **`--max-states` bounds the search as well**, and means the same thing here as in
  `mix extla.check` — how many states to explore. Exploring past a limit the task will refuse
  to draw is work thrown away.

  The cost is stated rather than hidden: a bounded search cannot name the real size of the
  state space, so the refusal says **more than N** instead of a number it does not have.
  The action is the same either way: raise the flag, or shrink the model.

  ## Exit codes

      0  the graph was written
      1  the spec has a violation; the graph was still written, with the
         counterexample emphasised, and it covers only what the search reached
      2  more states than `--max-states`, so nothing was drawn

  Exit code 1 is not a failure of the task. It is the same distinction `mix extla.check`
  draws: the picture is real, and it is a picture of an interrupted search.

  Exit code 2 is not a failure of the spec. It is `mix extla.check`'s code for a run that did
  not see the whole state space, and it is separate from 1 because "too big to draw" and
  "the design is wrong" are different answers.
  """

  use Mix.Task

  alias ExTLA.Mix.SpecTarget
  alias ExTLA.{ModelChecker, Spec, StateGraph}

  @switches [output: :string, max_states: :integer, format: :string]

  @impl Mix.Task
  def run(args) do
    Mix.Task.run("app.start")

    {opts, names} = OptionParser.parse!(args, strict: @switches)
    check_format!(Keyword.get(opts, :format, "dot"))

    case SpecTarget.resolve!(names) do
      [] ->
        Mix.raise("no ExTLA.Spec modules found. Name one, or `use ExTLA.Spec` in a module.")

      [module] ->
        visualize(module, opts)

      modules ->
        # A graph is one file and stdout is one stream, so unlike `mix extla.check` this
        # cannot fan out over a project's specs without deciding where each one goes.
        Mix.raise(
          "name one spec to visualize; got #{Enum.map_join(modules, ", ", &inspect/1)}. " <>
            "A state graph is one file, so there is no sensible place to put several."
        )
    end
  end

  defp visualize(module, opts) do
    spec = Spec.Compiled.from_module(module)
    max_states = Keyword.get(opts, :max_states, StateGraph.Export.default_max_states())

    # `liveness_graph: true` rather than `check_liveness: true`: the edge table is what the
    # export needs, and checking the temporal properties is work this task has no use for.
    # `ExTLA.StateGraph.to_dot/2` refuses without it, and refuses for a good reason — parent
    # pointers are a spanning tree — so the task asks for it rather than hitting that.
    #
    # `max_states` bounds the SEARCH as well as the rendering (#180). It was read after this
    # call and gated rendering only, so the search ran to the checker's own million-state
    # default — exploring up to a million states in order to draw none of them, and, where
    # that default was reached, drawing a truncated graph with no note and exiting 0.
    #
    # Bounding the search at the render limit removes the second case by construction rather
    # than by adding a note: past the limit there is nothing to draw, so a graph that is
    # drawn is one the search finished.
    {result, graph} =
      ModelChecker.explore(module, %{
        constants: SpecTarget.constants!(spec),
        liveness_graph: true,
        check_deadlock: false,
        max_states: max_states
      })

    # Asked before rendering rather than caught after, so the refusal reads like the task's
    # others instead of an `ArgumentError` with a stack trace. Its own exit code, and not
    # `Mix.raise`'s 1: `1` here already means "the spec has a violation", and a graph too
    # big to draw is not a finding about the spec. `2` is what `mix extla.check` returns for a
    # run that did not see the whole state space, which is exactly what this is.
    if message = StateGraph.Export.refusal(graph, max_states, "--max-states") do
      Mix.shell().error(message <> bounded_note(result, max_states))
      exit({:shutdown, 2})
    end

    dot = StateGraph.to_dot(graph, max_states: max_states, highlight: result.violation)

    emit(dot, opts[:output])
    note(result, opts[:output], graph)
    if result.status == :violation, do: exit({:shutdown, 1}), else: :ok
  end

  # The count in the refusal is the graph's, and the graph is what the search produced. Where
  # the search stopped AT the bound that number is not the state space's size, so it is not
  # offered as one — the moduledoc used to promise "the real count" and a bounded run cannot
  # know it. The overshoot is real: bounding at 500 yields 502, because the budget is checked
  # once per frontier expansion.
  defp bounded_note(%{status: :max_states_reached}, max_states) do
    "\n\nThe search stopped at --max-states, so the specification has MORE THAN " <>
      "#{max_states} states; the number above is where the search was when it stopped, not " <>
      "a census. Raise --max-states to find out how many, or to draw them."
  end

  defp bounded_note(_result, _max_states), do: ""

  defp emit(dot, nil), do: IO.puts(dot)

  defp emit(dot, path) do
    File.write!(path, dot)
    Mix.shell().info("wrote #{path}")
  end

  # To stderr-ish (`Mix.shell().info/1`) rather than into the DOT, so that
  # `mix extla.visualize X > g.dot` still produces a file Graphviz reads.
  defp note(result, output, graph) do
    if result.status == :violation do
      Mix.shell().info(
        "#{inspect(graph.spec.module)}: invariant :#{result.violation.property} is refuted at " <>
          "depth #{result.violation.length}. The graph#{if output, do: "", else: " above"} " <>
          "covers only what the search reached before stopping, and the counterexample is " <>
          "emphasised in it."
      )
    end
  end

  defp check_format!("dot"), do: :ok

  defp check_format!(deferred) when deferred in ~w(html mermaid) do
    Mix.raise(
      "--format #{deferred} is not built, and deliberately: 06-architecture.md §Phase 4 " <>
        "says DOT only, and §Deferred defers the HTML/D3 visualizer — \"DOT is enough, and " <>
        "a bespoke viewer is a maintenance sink\". Render the DOT and let Graphviz produce " <>
        "the format you want: `dot -Tsvg graph.dot`, or -Tpng, or -Tpdf."
    )
  end

  defp check_format!(other) do
    Mix.raise("unknown --format #{inspect(other)}; expected dot.")
  end

  @doc false
  # Exposed for `ExTLA.SpecOptionsTest`, which holds this and the specification's documented
  # option list to each other (#163). `extla.check` gained this at #134 and nothing else did, so
  # for six work items its section was the only flag list in the spec that stayed correct.
  def switches, do: @switches
end
