defmodule TLA.ProfileTest.Spec do
  @moduledoc """
  Three invariants whose costs differ by construction, so a report that ranks them has
  something to be right or wrong about.
  """
  use TLA.Spec

  constant :max, default: 200

  variable :n, type: 0..^max

  init do
    n = 0
  end

  action :tick do
    require n < ^max

    n = n + 1
  end

  action :reset do
    require n == ^max

    n = 0
  end

  # Deliberately the expensive one: a hundred iterations of arithmetic per evaluation, where
  # `cheap` is one comparison. The ratio is what the report has to get right, not the absolute
  # number.
  invariant :expensive do
    Enum.all?(1..100, fn i -> rem(i, 7) != 0 or n >= 0 end)
  end

  invariant :cheap do
    n >= 0
  end

  # Cheaper than the two counter reads can resolve. It exists to pin the calibration: without
  # the subtraction this reports the instrumentation's own cost, which is indistinguishable
  # from a real finding.
  invariant :trivial do
    true
  end
end

defmodule TLA.ProfileTest.LiveSpec do
  @moduledoc """
  A chain with a way back, so the graph has no deadlocked state and `check_liveness: true`
  actually reaches `TLA.ModelChecker.Liveness.check/3`.

  Its own module rather than a temporal added to `TLA.ProfileTest.Spec`: `check_liveness`
  defaults to false, so a spec that declares a temporal and is run without it collects the
  "declared and not checked" warning on every other test in this file.
  """
  use TLA.Spec

  constant :max, default: 5

  variable :n, type: 0..^max

  init do
    n = 0
  end

  action :tick do
    require n < ^max

    n = n + 1
  end

  action :reset do
    require n == ^max

    n = 0
  end

  fairness(:weak, [:tick])

  temporal :two_leads_to_four do
    (n == 2) ~> (n == 4)
  end
end

defmodule TLA.ProfileTest do
  @moduledoc """
  `TLA.Profile` — what each of the user's declarations cost, in reductions (#116, #130).

  `async: false` for one specific reason: "the count does not move under load" generates
  contention on purpose, and running it beside the async suite would make it both unreliable
  and rude.
  """
  use ExUnit.Case, async: false

  alias TLA.{ModelChecker, Profile}

  @spec_module TLA.ProfileTest.Spec

  # Constants explicitly: `default:` is resolved by `TLA.Mix.SpecTarget` for the mix task, not
  # by `ModelChecker.run/2`, so a test that leaves them out is refused by `type_ok`.
  @constants %{constants: %{max: 200}}

  defp run(config \\ %{}) do
    ModelChecker.run(@spec_module, Enum.into(config, Map.put(@constants, :profile, true)))
  end

  defp cost(profile, key), do: Map.fetch!(profile.declarations, key)

  # Every application of a transition, as the profile counted them.
  defp transitions_evaluated(profile) do
    profile.declarations
    |> Enum.filter(fn {key, _} -> match?({:transition, _}, key) end)
    |> Enum.map(fn {_, cost} -> cost.evaluations end)
    |> Enum.sum()
  end

  # The window, as a property rather than as a fixture's literals (#139).
  #
  # `model_checker.ex` applies a transition and increments `StateGraph.count_transition/1` on the
  # next line, unconditionally, with nothing between them — and `count_transition/1` has exactly
  # one caller. So for a profiled run these two numbers are the same measurement taken twice, once
  # by the graph and once by the instrumentation, and they can only disagree if something outside
  # the search is being counted.
  #
  # That is what makes this the right guard for #133 rather than a restatement of it: the defect
  # was `audit_log` reporting 6 against a graph that recorded 3, and it would have been caught
  # here on any spec, under any configuration, without anyone having predicted which.
  defp assert_window_is_the_search(result, context) do
    assert transitions_evaluated(result.profile) == result.transitions,
           "#{context}: the profile counted #{transitions_evaluated(result.profile)} transition " <>
             "applications, the search performed #{result.transitions}"

    result
  end

  describe "the window is the search, whatever stopped it" do
    # Each case is an axis on which the identity could fail for a reason that is NOT #133 —
    # a count that aggregates differently, a search that halts mid-expansion, a second run whose
    # profile could be paired with the first run's graph. Every one of them holds; where a case
    # is here to rule something out rather than to exercise a halt, the comment says what.

    test "a verifying run, where nothing halted the search" do
      run() |> assert_window_is_the_search("exhaustive")
    end

    test "a refuted run, whose counterexample is regenerated by replaying it" do
      # #133 itself: 6 against 3 before the fix.
      ModelChecker.run(TLA.Differential.AuditLog, %{
        constants: %{max_entries: 2},
        profile: true
      })
      |> assert_window_is_the_search("refuted")
    end

    # #212. The bracket closed after the liveness pass, so the denominator charged the states
    # liveness materialized again — against the module's own "the window is the search". The
    # pass is outside it now: the two denominators agree to within the liveness graph's edge
    # bookkeeping, which the search itself does.
    test "the run's denominator excludes the liveness pass" do
      config = %{constants: %{max: 5}, profile: true}
      without = ModelChecker.run(TLA.ProfileTest.LiveSpec, config).profile.run_reductions

      with_liveness =
        TLA.ProfileTest.LiveSpec
        |> ModelChecker.run(Map.put(config, :check_liveness, true))
        |> Map.fetch!(:profile)
        |> Map.fetch!(:run_reductions)

      assert with_liveness < without * 1.5,
             "liveness added #{with_liveness - without} reductions to a #{without}-reduction search"
    end

    test "a liveness run, which rebuilds every state to evaluate predicates over it" do
      # The larger half of #133: 11 against 6 before the fix. `check_liveness` must be passed —
      # it defaults to false, and a probe that omits it never reaches the code at all.
      ModelChecker.run(TLA.ProfileTest.LiveSpec, %{
        constants: %{max: 5},
        profile: true,
        check_liveness: true
      })
      |> assert_window_is_the_search("liveness")
    end

    test "a run halted by max_states, whose last expansion is partial" do
      result = run(%{max_states: 10}) |> assert_window_is_the_search("max_states")

      assert result.status == :max_states_reached
      assert result.coverage.bounded_by == :max_states
    end

    test "a run held back by a state constraint" do
      result =
        run(%{state_constraint: fn state -> state.n < 20 end})
        |> assert_window_is_the_search("state_constraint")

      assert result.coverage.bounded_by == :state_constraint
    end

    test "a deadlock, which is reported from an emptied frontier rather than mid-expansion" do
      # The distinction #137 drew for coverage. The profile should not care: both performed
      # exactly the work they performed, which is why `bounded_by` is `:none` here and the count
      # is still a census.
      result =
        ModelChecker.run(TLA.TestSpecs.Deadlocking, %{constants: %{max: 4}, profile: true})
        |> assert_window_is_the_search("deadlock")

      assert result.status == :violation
      assert result.deadlock
      assert result.coverage.bounded_by == :none
    end

    test "a parallel run, where the workers' contributions are summed" do
      # `Parallel.merge/2` sums per-worker profiles while `graph.transition_count` accumulates in
      # the coordinator. Nothing forces those two to aggregate alike, so it is asserted rather
      # than assumed — on a verifying run and on one that halts a worker mid-slice.
      run(%{workers: 4}) |> assert_window_is_the_search("workers, exhaustive")

      ModelChecker.run(TLA.Differential.AuditLog, %{
        constants: %{max_entries: 2},
        profile: true,
        workers: 4
      })
      |> assert_window_is_the_search("workers, refuted")
    end

    test "a symmetry-reduced run, and the two-run verification of one" do
      constants = %{constants: %{processes: MapSet.new([:p1, :p2])}}

      reduced =
        ModelChecker.run(
          TLA.TestSpecs.PerBinding,
          Map.merge(constants, %{profile: true, symmetry: [:processes]})
        )
        |> assert_window_is_the_search("symmetry")

      # `verify_symmetry: true` runs `search_and_finish/2` twice and returns the REDUCED result.
      # The identity would catch a profile paired with the wrong run's graph, which is the way
      # this could go wrong quietly; the equality below says which run was returned.
      verified =
        ModelChecker.run(
          TLA.TestSpecs.PerBinding,
          Map.merge(constants, %{profile: true, symmetry: [:processes], verify_symmetry: true})
        )
        |> assert_window_is_the_search("verify_symmetry")

      assert verified.transitions == reduced.transitions
      assert verified.distinct_states == reduced.distinct_states

      # And the reduction did something, so the case above is not vacuous.
      unreduced = ModelChecker.run(TLA.TestSpecs.PerBinding, Map.put(constants, :profile, true))
      assert reduced.distinct_states < unreduced.distinct_states
    end
  end

  describe "the measurement" do
    test "an unprofiled run reports no profile at all" do
      assert ModelChecker.run(@spec_module, @constants).profile == nil
    end

    test "an unprofiled run leaves the compiled spec's own closures in place" do
      # The wrapping happens on a copy made for the run. If it ever leaked into the module's
      # compiled form, every later run would pay for instrumentation nobody asked for — and
      # the leak would be invisible, because a wrapped closure returns the same value.
      before = TLA.Spec.Compiled.from_module(@spec_module)
      _profiled = run()
      assert TLA.Spec.Compiled.from_module(@spec_module) == before
    end

    test "an unprofiled run reaches the same verdict and counts as a profiled one" do
      plain = ModelChecker.run(@spec_module, @constants)
      profiled = run()

      assert plain.status == profiled.status
      assert plain.distinct_states == profiled.distinct_states
      assert plain.diameter == profiled.diameter
      assert plain.transitions == profiled.transitions
    end

    test "every declaration is present, including the ones that cost nothing" do
      profile = run().profile

      assert Map.keys(profile.declarations) |> Enum.sort() == [
               {:guard, :reset},
               {:guard, :tick},
               {:invariant, :cheap},
               {:invariant, :expensive},
               {:invariant, :trivial},
               {:invariant, :type_ok},
               {:transition, :reset},
               {:transition, :tick}
             ]
    end

    test "evaluation counts are exact, not sampled" do
      result = run()

      # An invariant is evaluated once per distinct state, so this is the one count that can be
      # checked against a number the run reports independently.
      for name <- [:expensive, :cheap, :trivial, :type_ok] do
        assert cost(result.profile, {:invariant, name}).evaluations == result.distinct_states,
               "#{name} was not evaluated once per distinct state"
      end
    end

    # The assertion above is correct and was incomplete, which is the pairing worth naming: it
    # checks INVARIANTS, which replay never evaluates, on a spec that VERIFIES, so no
    # counterexample is ever generated and the replay path is unreachable. The property it was
    # written to establish never met the condition under which it failed (#133).
    #
    # `audit_log` is the fixture because it is refuted by construction. Its trace replays
    # `record, record, compact`, and before the fix each of those applications was counted a
    # second time: `record` reported 4 against a search that applied it twice, `compact` 2
    # against one.
    test "a refuted spec counts what the search applied, not what replaying its trace re-applied" do
      result =
        ModelChecker.run(TLA.Differential.AuditLog, %{
          constants: %{max_entries: 2},
          profile: true
        })

      assert result.status == :violation
      assert result.violation.actions == [:record, :record, :compact]

      # From `<<>>` and from `<<1>>`; `<<1,2>>` fails `record`'s guard.
      assert cost(result.profile, {:transition, :record}).evaluations == 2

      # Only `<<1,2>>` passes `compact`'s guard.
      assert cost(result.profile, {:transition, :compact}).evaluations == 1
    end

    # The other half of the same fix: `Trace.from/4` applies transitions and nothing else, so
    # guards, invariants and action properties were never inflated. Asserted so that a future
    # attempt to close the window by subtracting rather than by not counting cannot pass — that
    # would have to guess at these, and guessing wrong is invisible without them.
    test "the kinds replay never touches were right before the fix and stay right after it" do
      result =
        ModelChecker.run(TLA.Differential.AuditLog, %{
          constants: %{max_entries: 2},
          profile: true
        })

      for key <- [
            {:guard, :record},
            {:guard, :compact},
            {:invariant, :bounded_log},
            {:invariant, :type_ok},
            {:action_property, :log_only_grows}
          ] do
        assert cost(result.profile, key).evaluations == result.distinct_states,
               "#{inspect(key)} moved; only {:transition, _} was ever inflated"
      end
    end

    # The larger half of #133, and the one its own probe first appeared to rule out. Liveness
    # evaluates its predicates by materializing EVERY state through `graph.spec`'s transitions
    # (`Liveness.evaluate/2` → `materialize/3`), once per node of the spanning tree — so before
    # the fix a liveness run was inflated by roughly a whole extra search, with no violation
    # required and no counterexample involved. Measured on this spec: `tick` reported 10 against
    # a search that applied it 5 times.
    #
    # It hid behind `check_liveness: false`, which is the default. A probe that does not pass it
    # never reaches `check_temporals/1`'s third clause and sees no inflation at all, which is a
    # fixture failing to produce the condition — the same shape as the gap above.
    test "a liveness run counts the search, not the states liveness rebuilt to evaluate over" do
      result =
        ModelChecker.run(TLA.ProfileTest.LiveSpec, %{
          constants: %{max: 5},
          profile: true,
          check_liveness: true
        })

      assert result.status == :ok
      assert result.distinct_states == 6

      # The search: `tick` from n=0..4, `reset` from n=5 back to an already-seen n=0.
      assert cost(result.profile, {:transition, :tick}).evaluations == 5
      assert cost(result.profile, {:transition, :reset}).evaluations == 1
    end

    test "the OTP release is recorded, because a count is only comparable within one" do
      assert run().profile.otp_version == List.to_string(:erlang.system_info(:otp_release))
    end
  end

  describe "what it ranks" do
    test "the expensive invariant outranks the cheap one, by about the ratio of the work" do
      profile = run().profile

      expensive = cost(profile, {:invariant, :expensive})
      cheap = cost(profile, {:invariant, :cheap})

      assert expensive.reductions > cheap.reductions * 10,
             "expected `expensive` to dominate `cheap`, got #{expensive.reductions} vs " <>
               "#{cheap.reductions}"

      # And it is the first row the reader sees.
      assert profile |> Profile.format() |> String.split("\n") |> Enum.find(&(&1 =~ ~r/^\s+\w/)) =~
               "expensive"
    end

    test "the calibration is subtracted, so a trivial declaration reports about nothing" do
      profile = run().profile

      trivial = cost(profile, {:invariant, :trivial})

      # Not exactly zero — `true` still costs the call the wrapper cannot subtract, which is
      # the call an unprofiled run would also pay. What matters is that it is not the
      # instrumentation's cost showing up as a finding.
      assert trivial.reductions <= trivial.evaluations * 3,
             "`trivial` reports #{trivial.reductions} reductions over #{trivial.evaluations} " <>
               "evaluations — the calibration is not being subtracted"
    end

    test "the share of the run is reported, and the declarations are a part of it" do
      profile = run().profile

      total = profile.declarations |> Map.values() |> Enum.map(& &1.reductions) |> Enum.sum()

      assert profile.run_reductions > total,
             "the declarations cannot cost more than the run that called them"

      assert Profile.format(profile) =~
               ~r/All declarations: [\d,]+ reductions, \d+\.\d% of the run/
    end

    # #199. Declaration costs were collected per worker and summed, while `run_reductions` was
    # the coordinator's own `Process.info(:reductions)` — which under `workers: n` does almost
    # none of the work. The numerator counted the workers and the denominator excluded them:
    # the same spec read 12% at one worker and 91% at eight, and the advice inverted. The
    # guarding test ran at one worker, where the two brackets coincide.
    test "the share of the run does not depend on the worker count" do
      # Bounded buffer rather than this file's chain spec, deliberately. The chain has ONE
      # state per BFS level, so a parallel run of it is a task per level per state and the
      # scheduling is three times the search — 6% at one worker, 2% at four, both honest. A
      # share that says "the machinery is most of this run" is the right answer about
      # parallelising a chain; the defect was a share that changed by a factor of seven on a
      # spec where the work did not.
      {:ok, constants} =
        TLA.Differential.BoundedBuffer
        |> TLA.Spec.Compiled.from_module()
        |> TLA.Spec.Compiled.resolve_constants()

      share_at = fn workers ->
        TLA.Differential.BoundedBuffer
        |> ModelChecker.run(%{constants: constants, profile: true, workers: workers})
        |> Map.fetch!(:profile)
        |> share()
      end

      one = share_at.(1)
      four = share_at.(4)

      # Parallel scheduling costs reductions of its own — about a sixth more on this spec — so
      # the denominators are not identical. The defect was 12% against 91%.
      assert_in_delta one, four, 3.0, "share at workers: 1 is #{one}%, at workers: 4 is #{four}%"

      assert one < 25.0 == four < 25.0,
             "the advice threshold gives different verdicts at one worker and four"
    end
  end

  defp share(profile) do
    total = profile.declarations |> Map.values() |> Enum.map(& &1.reductions) |> Enum.sum()
    total * 100 / profile.run_reductions
  end

  describe "stability — the property the unit was chosen for" do
    # The bound is ABSOLUTE — two reductions per evaluation — and that is the whole claim.
    #
    # A floor can only be pushed UP, by an evaluation that never ran uninterrupted, so under
    # adversarial load a short run may not observe the true minimum and lands a reduction or two
    # high. It cannot land low. So this is a near-equality rather than an equality, and it does
    # not grow with load: on a 304 reds/eval declaration two reductions is 0.7%, and it is still
    # two reductions when the machine is at load 32. Wall time on the same workload spread 100.3%.
    #
    # Asserted this way rather than as a percentage because a percentage would be generous to
    # the expensive declarations and meaningless for the cheap ones, and it is the cheap ones
    # where a regression would hide.
    @margin 2

    defp counts(profile) do
      Map.new(profile.declarations, fn {key, entry} -> {key, entry.evaluations} end)
    end

    defp floors(profile) do
      Map.new(profile.declarations, fn {key, entry} -> {key, entry.per_eval} end)
    end

    # Settled floors only (#248). `reset` is applied in exactly one state of this fixture, so
    # its "floor" is one sample and an excursion inside that one bracket is the reported cost:
    # 2 on a quiet machine, 29 under load, on three CI runs. That is not the floor moving; it
    # is a floor that does not exist yet, and `Profile` now says so on the row. The exclusion
    # is not silent — the test below asserts the marking — and the message carries each
    # item's evaluation count so a future drift names its sample size.
    defp drift(a, b) do
      for {key, %{settled: true, per_eval: left, evaluations: n}} <- a.declarations,
          right = Map.fetch!(floors(b), key),
          abs(left - right) > @margin,
          do: {key, left, right, {:evaluations, n}}
    end

    test "two runs of the same spec agree on every count exactly and every cost to within two" do
      one = run().profile
      other = run().profile

      # Evaluation counts are a function of the search, so these are exact under any conditions.
      assert counts(one) == counts(other)
      assert drift(one, other) == []
    end

    # The one-sample item is reported and marked, never dropped: dropping it would be the
    # exclusion above happening in the report instead of the test.
    test "a floor over too few evaluations is marked not settled, and the rest are settled" do
      profile = run().profile

      assert %{evaluations: 1, settled: false} = profile.declarations[{:transition, :reset}]
      assert %{settled: true} = profile.declarations[{:transition, :tick}]

      assert Profile.format(profile) =~ "reset"
      assert Profile.format(profile) =~ "floor over 1 evaluation, not settled"
      refute Profile.format(profile) =~ ~r/tick.*not settled/
    end

    test "the cost is the floor times the evaluations, so it is not an average" do
      for {_key, entry} <- run().profile.declarations do
        assert entry.reductions == entry.per_eval * entry.evaluations

        # And the floor is a floor: the counter cannot have accumulated less than it.
        assert entry.observed >= entry.reductions
      end
    end

    test "the count does not move under machine load, which is why it is not milliseconds" do
      quiet = run().profile

      busy =
        for _ <- 1..32 do
          spawn(fn -> Stream.iterate(0, &(&1 + 1)) |> Enum.each(fn _ -> :ok end) end)
        end

      loaded =
        try do
          run().profile
        after
          Enum.each(busy, &Process.exit(&1, :kill))
        end

      # The counts are untouched by load — the search did the same work — and the costs move by
      # at most the margin, which is what a wall clock cannot promise at any figure.
      assert counts(quiet) == counts(loaded)

      moved = drift(quiet, loaded)

      assert moved == [],
             "the profile moved under load by more than #{@margin} reductions per evaluation, " <>
               "which is the one thing reductions are here to avoid: #{inspect(moved)}"
    end
  end

  describe "merge" do
    # `merge/2` combines RAW contributions — what `collect/1` reads out of a worker's process
    # dictionary — and `finalize/2` runs once over the result. Built by hand rather than from
    # two runs, because two runs give finalized profiles and finalizing twice would subtract
    # the calibration twice. That ordering is #131's whole subject.
    defp contribution(entries, run_reductions) do
      %Profile{
        declarations: Map.new(entries),
        calibration: %{2 => 1, 3 => 1},
        run_reductions: run_reductions,
        otp_version: "29"
      }
    end

    test "counts and observed totals add; the per-evaluation floor takes the smaller" do
      a =
        contribution(
          [{{:invariant, :x}, %{evaluations: 10, reductions: 0, per_eval: 51, observed: 530}}],
          1_000
        )

      b =
        contribution(
          [{{:invariant, :x}, %{evaluations: 4, reductions: 0, per_eval: 41, observed: 170}}],
          400
        )

      merged = Profile.merge(a, b)
      entry = Map.fetch!(merged.declarations, {:invariant, :x})

      assert entry.evaluations == 14
      assert entry.observed == 700
      assert entry.per_eval == 41, "the floor is a minimum, not a sum or an average"
      assert merged.run_reductions == 1_400

      # And the cost falls out of the merged floor, once.
      finalized = Profile.finalize(merged, 1_400)
      assert Map.fetch!(finalized.declarations, {:invariant, :x}).per_eval == 40
      assert Map.fetch!(finalized.declarations, {:invariant, :x}).reductions == 560
    end

    test "a worker that evaluated nothing does not drag the floor to zero" do
      seen =
        contribution(
          [{{:invariant, :x}, %{evaluations: 10, reductions: 0, per_eval: 51, observed: 530}}],
          1_000
        )

      idle =
        contribution(
          [{{:invariant, :x}, %{evaluations: 0, reductions: 0, per_eval: 0, observed: 0}}],
          0
        )

      # This is the bug the shape invites: `min(51, 0)` is 0, and a worker whose slice never
      # reached this declaration would silently zero its cost.
      assert Map.fetch!(Profile.merge(seen, idle).declarations, {:invariant, :x}).per_eval == 51
      assert Map.fetch!(Profile.merge(idle, seen).declarations, {:invariant, :x}).per_eval == 51
    end
  end

  describe "calibration" do
    test "is stable across calls, which is what makes subtracting it sound" do
      constants = for _ <- 1..5, do: Profile.calibrate()

      assert length(Enum.uniq(constants)) == 1,
             "the instrumentation constant moved between calibrations: #{inspect(constants)}"
    end

    test "is small enough to leave a cheap declaration measurable" do
      # One BIF call. If this grows, cheap declarations start reporting the harness instead of
      # themselves, and the report stops ranking anything.
      assert Profile.calibrate()[2] <= 3
      assert Profile.calibrate()[3] <= 3
    end

    # `calibrate/0` carries a comment saying it is public so a test can assert the constant
    # is stable — the two tests above are that test. `calibration_samples/0` stood beside it
    # with no such claim, no caller anywhere, and no assertion: a published function whose
    # only effect was a row in `API_SURFACE.md`. #317 deleted it rather than inventing a use.
    test "and the accessor nothing called is gone, with nothing left calling it" do
      refute function_exported?(Profile, :calibration_samples, 0)

      # This file names it in the assertion itself, so it is the one exclusion.
      callers =
        for path <- Path.wildcard("{lib,test,bench,ledger,bin,scripts}/**/*.{ex,exs}"),
            Path.expand(path) != __ENV__.file,
            File.read!(path) =~ "calibration_samples(",
            do: path

      assert callers == []
    end
  end

  describe "the rendered report" do
    test "carries exactly one wall-time figure and no per-declaration milliseconds" do
      report = Profile.format(run().profile)

      refute report =~ ~r/\bms\b/
      refute report =~ "µs"
    end

    test "names the calibration it subtracted and the OTP it was taken on" do
      report = Profile.format(run().profile)

      assert report =~ ~r/Instrumentation calibrated at \d+\/\d+ reductions per evaluation/
      assert report =~ "OTP #{:erlang.system_info(:otp_release)}"
    end

    # The advice is for the case the report will usually be read in — a large model where the
    # checker's own machinery dominates. This spec is small enough that its declarations really
    # are about half the run, so the line correctly does NOT appear for it, and testing both
