defmodule TLA.DifferentialTest do
  @moduledoc """
  The Phase 1 acceptance gate (`spec/08-decisions.md` D-9): for every corpus
  entry, ExTLA and TLC must agree on the number of distinct reachable states,
  whether each invariant holds, and the length of the shortest counterexample
  where one exists.

  `expected.json` is TLC's answer, generated by `bin/tlc-expected` and checked
  against a live TLC run by CI — so this test compares ExTLA to an oracle, not
  to its own output from last week. That distinction is the whole point of
  landing the corpus before the checker: a checker that explores 15 of 16 states
  reports "no violation found" in exactly the same words as one that explores
  all 16.
  """
  use ExUnit.Case, async: true

  alias TLA.ModelChecker

  @corpus Path.expand("../differential", __DIR__)

  # Each entry names its ExTLA spec module and the constants TLC was run with.
  # `die_hard` has none: the jugs are in the module.
  @entries [
    %{name: "die_hard", module: TLA.Differential.DieHard, constants: %{}}
  ]

  for entry <- @entries do
    describe "#{entry.name}" do
      @describetag entry: entry

      setup do
        entry = unquote(Macro.escape(entry))

        expected =
          Path.join([@corpus, entry.name, "expected.json"]) |> File.read!() |> Jason.decode!()

        %{entry: entry, expected: expected}
      end

      test "explores the same number of distinct states as TLC", ctx do
        result = check(ctx.entry, invariants: [])

        assert result.distinct_states == ctx.expected["distinct_states"]
      end

      # Catches the narrower failure of a search that stopped early but
      # coincidentally reached the same state count.
      test "reaches the same search depth as TLC", ctx do
        result = check(ctx.entry, invariants: [])

        assert result.diameter == ctx.expected["diameter"]
      end

      test "agrees with TLC about deadlock", ctx do
        result = check(ctx.entry, invariants: [])

        assert result.deadlock == ctx.expected["deadlock"]
      end

      test "agrees with TLC on every invariant", ctx do
        spec = TLA.Spec.Compiled.from_module(ctx.entry.module)

        for {tlc_name, verdict} <- ctx.expected["invariants"] do
          name = invariant_name!(spec, tlc_name)
          result = check(ctx.entry, invariants: [name])

          case verdict do
            "holds" ->
              assert result.status == :ok,
                     "#{tlc_name} holds under TLC but ExTLA reported #{inspect(result.status)}"

            %{"violated_at" => depth} ->
              assert result.status == :violation
              assert result.violation.property == name

              # The shortest counterexample, in states. TLC searches
              # breadth-first and so does this checker, so a longer trace here
              # would mean the search order has drifted -- and a checker that
              # hands back a longer trace than necessary is handing back a worse
              # explanation of the same bug.
              assert result.violation.length == depth
          end
        end
      end

      test "the counterexample replays to the state that violates the invariant", ctx do
        violated =
          Enum.find(ctx.expected["invariants"], fn {_, verdict} -> is_map(verdict) end)

        if violated do
          {tlc_name, _} = violated
          spec = TLA.Spec.Compiled.from_module(ctx.entry.module)
          name = invariant_name!(spec, tlc_name)
          result = check(ctx.entry, invariants: [name])
          invariant = Enum.find(spec.invariants, &(&1.name == name))

          states = result.violation.states
          {before, [last]} = Enum.split(states, -1)

          assert Enum.all?(before, &invariant.predicate.(ctx.entry.constants, &1)),
                 "a state before the last one already violated #{name}, so the trace is not minimal"

          refute invariant.predicate.(ctx.entry.constants, last)
        end
      end
    end
  end

  defp check(entry, opts) do
    ModelChecker.run(entry.module, Map.merge(%{constants: entry.constants}, Map.new(opts)))
  end

  # The .cfg names an invariant `NotSolved`; the DSL spec names it `:not_solved`.
  # Resolving through the compiled spec rather than String.to_existing_atom/1
  # also catches the case worth catching: an invariant TLC checked that the
  # ExTLA spec does not have, which would otherwise pass by not being compared.
  defp invariant_name!(spec, tlc_name) do
    underscored = Macro.underscore(tlc_name)

    case Enum.find(spec.invariants, &(Atom.to_string(&1.name) == underscored)) do
      nil ->
        flunk(
          "TLC checked #{tlc_name}, but #{inspect(spec.module)} declares no invariant " <>
            "#{underscored}. Declared: " <>
            Enum.map_join(spec.invariants, ", ", &inspect(&1.name)) <> "."
        )

      invariant ->
        invariant.name
    end
  end
end
