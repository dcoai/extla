defmodule ExTLA.SecondStartReplayTest do
  @moduledoc """
  A path that starts from a spec's second `init` block is replayed from that block (#392).

  The graph keeps no states (D-5), so every trace, and every `StateGraph.state_at/2`, is
  regenerated by replaying the path from the root's `init` block, which the root records as
  `init_index`. Read it wrong and a replay starts from the wrong state. It is still a legal
  behaviour, so only a property it no longer refutes, or a state that is no longer the one
  asked for, can tell.

  Before this file, the one test that noticed was a generated property, and only on the seeds
  that built a two-`init` spec refuted from its second block: mutant `wrong_init_index`
  survived 10 seeds of 100. These tests are that shape, fixed, so they notice on every run.
  """
  use ExUnit.Case, async: true

  alias ExTLA.{ModelChecker, StateGraph, Trace}
  alias ExTLA.TestSpecs.{TwoStarts, WrongFromTheSecondStart}

  @right_start %{side: :right, steps: 0}

  describe "a counterexample from the second start" do
    @describetag verifies:
                   "spec/04-layer2-model-checker.md#Layer 2: Specification DSL + Model Checker/Module: `ExTLA.Trace`"

    test "an invariant's counterexample starts where the second init block does, and is admitted" do
      result =
        ModelChecker.run(WrongFromTheSecondStart, %{
          invariants: [:right_never_reaches_two],
          action_properties: []
        })

      assert %Trace{property: :right_never_reaches_two} = trace = result.violation
      assert hd(trace.states) == @right_start
      assert List.last(trace.states) == %{side: :right, steps: 2}
      assert Trace.validate(trace, WrongFromTheSecondStart, %{}) == :ok
    end

    test "and so does an action property's" do
      result =
        ModelChecker.run(WrongFromTheSecondStart, %{
          invariants: [],
          action_properties: [:right_never_steps_to_two]
        })

      assert %Trace{property: :right_never_steps_to_two} = trace = result.violation
      assert hd(trace.states) == @right_start
      assert Trace.validate(trace, WrongFromTheSecondStart, %{}) == :ok
    end
  end

  describe "a state regenerated by replay" do
    @describetag verifies:
                   "spec/04-layer2-model-checker.md#Layer 2: Specification DSL + Model Checker/Module: `ExTLA.ModelChecker`/State Graph"

    # Every state, not a sample: half of them descend from the second block, and a state
    # replayed from the first lands on a different state with a different id.
    test "is the state its id names, from either start" do
      {_result, graph} =
        ModelChecker.explore(TwoStarts, %{check_deadlock: false, liveness_graph: true})

      ids = Map.keys(graph.edges)
      assert length(ids) == 6

      for id <- ids do
        assert StateGraph.id_of(graph, StateGraph.state_at(graph, id)) == id
      end

      assert @right_start in Enum.map(ids, &StateGraph.state_at(graph, &1))
    end
  end
end
